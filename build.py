"""Build dist/lsu-moodle-dark.user.js from the extension sources.

The userscript is for browsers without Chrome-extension support (Chrome for Android
has none): Firefox for Android with Violentmonkey/Tampermonkey, Chromium-based
Android browsers with extension support, and Safari on iOS via the Userscripts app.

It bundles the stylesheets and content.js unchanged, plus a small shim that stands in for
chrome.storage (backed by the site's localStorage) and replaces the popup with
userscript menu commands (or a small floating button where menus aren't supported).

Usage:  python build.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).parent
manifest = json.loads((ROOT / "manifest.json").read_text(encoding="utf-8"))
read = lambda f: (ROOT / f).read_text(encoding="utf-8")
# Each content script in the manifest is one site: its URL patterns and stylesheets.
# The first stylesheet (base.css) is shared, the second is the site's own.
sites = manifest["content_scripts"]
base_css = sites[0]["css"][0]
assert all(s["css"][0] == base_css and len(s["css"]) == 2 for s in sites), "expected [base.css, <site>.css]"
content_js = (ROOT / "content.js").read_text(encoding="utf-8")

REPO = "https://github.com/g34rmeister/moodle-dark-mode"
RAW = "https://raw.githubusercontent.com/g34rmeister/moodle-dark-mode/main"

MATCHES = "".join(f"// @match        {m}\n" for s in sites for m in s["matches"])

HEADER = f"""// ==UserScript==
// @name         {manifest["name"]}
// @namespace    lsu-moodle-dark
// @version      {manifest["version"]}
// @description  {manifest["description"].rstrip(".")} (userscript build for mobile browsers)
{MATCHES}// @run-at       document-start
// @homepageURL  {REPO}
// @supportURL   {REPO}/issues
// @updateURL    {RAW}/dist/lsu-moodle-dark.user.js
// @downloadURL  {RAW}/dist/lsu-moodle-dark.user.js
// @grant        GM_registerMenuCommand
// @grant        GM.registerMenuCommand
// ==/UserScript==
// Generated by build.py from the .css files + content.js. Edit those, not this file.
"""

SHIM = r"""
// ---------- chrome.storage stand-in (localStorage, synced across tabs) ----------
const STORE_KEY = "lsu-moodle-dark";
const readStore = () => { try { return JSON.parse(localStorage.getItem(STORE_KEY)) || {}; } catch { return {}; } };
const storageListeners = [];
const emit = (changes) => storageListeners.forEach((fn) => fn(changes));
const chrome = {
  storage: {
    sync: {
      get(defaults, cb) { cb({ ...defaults, ...readStore() }); },
      set(values) {
        const old = readStore();
        try { localStorage.setItem(STORE_KEY, JSON.stringify({ ...old, ...values })); } catch {}
        const changes = {};
        for (const k in values) changes[k] = { oldValue: old[k], newValue: values[k] };
        emit(changes);
      },
    },
    onChanged: { addListener(fn) { storageListeners.push(fn); } },
  },
};
window.addEventListener("storage", (e) => {
  if (e.key !== STORE_KEY) return;
  let oldV = {}, newV = {};
  try { oldV = JSON.parse(e.oldValue) || {}; newV = JSON.parse(e.newValue) || {}; } catch {}
  const changes = {};
  for (const k of new Set([...Object.keys(oldV), ...Object.keys(newV)])) {
    if (oldV[k] !== newV[k]) changes[k] = { oldValue: oldV[k], newValue: newV[k] };
  }
  emit(changes);
});

// ---------- stylesheet (the extension injects this via the manifest) ----------
const style = document.createElement("style");
style.id = "lsu-moodle-dark-css";
// The site's own stylesheet: the first whose URL patterns match this page
const SITES = __SITES__;
// Match pattern -> RegExp: `*` is any run of characters, everything else literal
const glob = (p) => new RegExp("^" + p.split("*").map((s) => s.replace(/[.?+^$()[\]{}|\\]/g, "\\$&")).join(".*") + "$");
// An about:blank frame (the editor's iframe) belongs to the page that made it
const pageUrl = () => {
  let w = window;
  try { while (w.location.protocol === "about:" && w !== w.parent) w = w.parent; return w.location.href; }
  catch { return location.href; }
};
const site = SITES.find((s) => s.matches.some((m) => glob(m).test(pageUrl())));
style.textContent = __BASE_CSS__ + (site ? site.css : "");
// At document-start some engines (WebKit/Safari) run us before <html> exists, and
// in an editor iframe the page's document.open/write later replaces <html> along
// with this <style>. So (re)attach it whenever it is missing. content.js does the
// same for its classes (see handleMutations).
const attachStyle = () => {
  if (!style.isConnected && document.documentElement) (document.head || document.documentElement).appendChild(style);
};
attachStyle();
new MutationObserver(attachStyle).observe(document, { childList: true });
"""

TOGGLES = r"""
// ---------- toggles (the extension uses its toolbar popup) ----------
const settings = () => ({ ...DEFAULTS, ...readStore() }); // DEFAULTS: from content.js
// Flips what you see right now (in Auto mode that also leaves Auto)
// (turning on also re-enables this site, if it was switched off on its own)
const toggleDark = () => chrome.storage.sync.set(isDark() ? { enabled: false, auto: false } : { enabled: true, auto: false, [SITE_KEY]: true });
const toggleAuto = () => chrome.storage.sync.set({ auto: !settings().auto, enabled: true });
const toggleAmoled = () => chrome.storage.sync.set({ amoled: !settings().amoled, enabled: true });
// This site only (SITE_KEY: from content.js), for when one site breaks
const toggleSite = () => chrome.storage.sync.set({ [SITE_KEY]: settings()[SITE_KEY] === false });
const registerMenu =
  (typeof GM_registerMenuCommand === "function" && GM_registerMenuCommand) ||
  (typeof GM !== "undefined" && GM && typeof GM.registerMenuCommand === "function" && GM.registerMenuCommand.bind(GM));
if (window.top === window) {
  if (registerMenu) {
    registerMenu("Toggle dark mode", toggleDark);
    registerMenu("Toggle AMOLED black", toggleAmoled);
    registerMenu("Toggle follow system (Auto)", toggleAuto);
    registerMenu("Toggle on this site only", toggleSite);
  } else {
    // No menu API (e.g. iOS Userscripts): a small floating button.
    // Tap = dark on/off, long-press = AMOLED on/off.
    const addButton = () => {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.textContent = "◐";
      btn.setAttribute("aria-label", "Toggle dark mode (long-press for AMOLED)");
      Object.assign(btn.style, {
        position: "fixed", left: "12px", bottom: "12px", zIndex: 2147483647,
        width: "40px", height: "40px", borderRadius: "50%", border: "1px solid #fdd023",
        background: "#1e1b26", color: "#fdd023", fontSize: "20px", lineHeight: "1",
        opacity: "0.7", padding: "0",
      });
      let timer, longPressed = false;
      btn.addEventListener("pointerdown", () => {
        longPressed = false;
        timer = setTimeout(() => { longPressed = true; toggleAmoled(); }, 600);
      });
      btn.addEventListener("pointerup", () => clearTimeout(timer));
      btn.addEventListener("pointerleave", () => clearTimeout(timer));
      btn.addEventListener("click", () => { if (!longPressed) toggleDark(); });
      document.body.appendChild(btn);
    };
    // Some managers inject after DOMContentLoaded despite @run-at document-start
    if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", addButton);
    else addButton();
  }
}
"""

out = (
    HEADER
    + "(() => {\n"
    + SHIM.replace("__BASE_CSS__", json.dumps(read(base_css))).replace(
        "__SITES__", json.dumps([{"matches": s["matches"], "css": read(s["css"][1])} for s in sites], indent=None))
    + "\n// ---------- content.js ----------\n"
    + content_js
    + TOGGLES
    + "})();\n"
)

dist = ROOT / "dist"
dist.mkdir(exist_ok=True)
# Always LF, so a build on Windows produces the same file as one on Linux/macOS
(dist / "lsu-moodle-dark.user.js").write_text(out, encoding="utf-8", newline="\n")
print(f"wrote dist/lsu-moodle-dark.user.js ({len(out) // 1024} KB, v{manifest['version']})")

# ---------- Browser packages: only what the extension loads at runtime ----------
# One source manifest (manifest.json, which Chromium browsers load as-is for "Load
# unpacked"), plus per-browser tweaks. Each target gets an unpacked folder under
# dist/build/ (for local testing) and a zip for its store.
import shutil
import zipfile

css_files = list(dict.fromkeys(f for s in sites for f in s["css"]))
runtime = [*css_files, "content.js", "popup.html", "popup.js",
           *[f"icons/icon-{s}.png" for s in (16, 32, 48, 128)]]
missing = [f for f in runtime if not (ROOT / f).exists()]
if missing:
    raise SystemExit(f"missing files for the store package: {missing} (run make_icons.py?)")


def firefox_manifest(m):
    m = json.loads(json.dumps(m))  # deep copy
    m["browser_specific_settings"] = {
        "gecko": {
            # Fixed forever once published: Firefox keys settings and updates on it
            "id": "lsu-moodle-dark@g34rmeister.github.io",
            # 140: first version with the data-consent key below, which
            # addons.mozilla.org requires for new extensions (also the 140 ESR)
            "strict_min_version": "140.0",
            "data_collection_permissions": {"required": ["none"]},
        },
        "gecko_android": {"strict_min_version": "142.0"},
    }
    return m


TARGETS = {
    # Chrome, Edge, Brave, Opera, Vivaldi
    "chrome": (manifest, "Chrome Web Store / Edge Add-ons / Opera add-ons"),
    # Firefox desktop + Android
    "firefox": (firefox_manifest(manifest), "addons.mozilla.org"),
}

for name, (m, store) in TARGETS.items():
    unpacked = dist / "build" / name
    shutil.rmtree(unpacked, ignore_errors=True)
    unpacked.mkdir(parents=True)
    (unpacked / "manifest.json").write_text(json.dumps(m, indent=2) + "\n", encoding="utf-8", newline="\n")
    for f in runtime:
        (unpacked / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / f, unpacked / f)
    zip_path = dist / f"lsu-moodle-dark-{manifest['version']}-{name}.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for f in ["manifest.json", *runtime]:
            z.write(unpacked / f, f)
    print(f"wrote dist/{zip_path.name} (upload to {store}; unpacked copy in dist/build/{name}/)")
