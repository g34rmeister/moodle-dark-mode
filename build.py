"""Build dist/lsu-moodle-dark.user.js from the extension sources.

The userscript is for browsers without Chrome-extension support (Chrome for Android
has none): Firefox for Android with Violentmonkey/Tampermonkey, Chromium-based
Android browsers with extension support, and Safari on iOS via the Userscripts app.

It bundles dark.css and content.js unchanged, plus a small shim that stands in for
chrome.storage (backed by the site's localStorage) and replaces the popup with
userscript menu commands (or a small floating button where menus aren't supported).

Usage:  python build.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).parent
manifest = json.loads((ROOT / "manifest.json").read_text(encoding="utf-8"))
css = (ROOT / "dark.css").read_text(encoding="utf-8")
content_js = (ROOT / "content.js").read_text(encoding="utf-8")

HEADER = f"""// ==UserScript==
// @name         {manifest["name"]}
// @namespace    lsu-moodle-dark
// @version      {manifest["version"]}
// @description  {manifest["description"].rstrip(".")} (userscript build for mobile browsers)
// @match        https://moodle.lsu.edu/*
// @run-at       document-start
// @grant        GM_registerMenuCommand
// @grant        GM.registerMenuCommand
// ==/UserScript==
// Generated by build.py from dark.css + content.js. Edit those, not this file.
"""

SHIM = r"""
// ---------- chrome.storage stand-in (localStorage, synced across tabs) ----------
const STORE_KEY = "lsu-moodle-dark";
const readStore = () => { try { return JSON.parse(localStorage.getItem(STORE_KEY)) || {}; } catch { return {}; } };
const storageListeners = [];
const emit = (changes) => storageListeners.forEach((fn) => fn(changes));
const chrome = {
  storage: {
    sync: {
      get(defaults, cb) { cb({ ...defaults, ...readStore() }); },
      set(values) {
        const old = readStore();
        try { localStorage.setItem(STORE_KEY, JSON.stringify({ ...old, ...values })); } catch {}
        const changes = {};
        for (const k in values) changes[k] = { oldValue: old[k], newValue: values[k] };
        emit(changes);
      },
    },
    onChanged: { addListener(fn) { storageListeners.push(fn); } },
  },
};
window.addEventListener("storage", (e) => {
  if (e.key !== STORE_KEY) return;
  let oldV = {}, newV = {};
  try { oldV = JSON.parse(e.oldValue) || {}; newV = JSON.parse(e.newValue) || {}; } catch {}
  const changes = {};
  for (const k of new Set([...Object.keys(oldV), ...Object.keys(newV)])) {
    if (oldV[k] !== newV[k]) changes[k] = { oldValue: oldV[k], newValue: newV[k] };
  }
  emit(changes);
});

// ---------- stylesheet (the extension injects this via the manifest) ----------
const style = document.createElement("style");
style.id = "lsu-moodle-dark-css";
style.textContent = __CSS__;
(document.head || document.documentElement).appendChild(style);
"""

TOGGLES = r"""
// ---------- toggles (the extension uses its toolbar popup) ----------
const settings = () => ({ enabled: true, amoled: false, ...readStore() });
const toggleDark = () => chrome.storage.sync.set({ enabled: !settings().enabled });
const toggleAmoled = () => chrome.storage.sync.set({ amoled: !settings().amoled, enabled: true });
const registerMenu =
  (typeof GM_registerMenuCommand === "function" && GM_registerMenuCommand) ||
  (typeof GM !== "undefined" && GM && typeof GM.registerMenuCommand === "function" && GM.registerMenuCommand.bind(GM));
if (window.top === window) {
  if (registerMenu) {
    registerMenu("Toggle dark mode", toggleDark);
    registerMenu("Toggle AMOLED black", toggleAmoled);
  } else {
    // No menu API (e.g. iOS Userscripts): a small floating button.
    // Tap = dark on/off, long-press = AMOLED on/off.
    const addButton = () => {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.textContent = "◐";
      btn.setAttribute("aria-label", "Toggle dark mode (long-press for AMOLED)");
      Object.assign(btn.style, {
        position: "fixed", left: "12px", bottom: "12px", zIndex: 2147483647,
        width: "40px", height: "40px", borderRadius: "50%", border: "1px solid #fdd023",
        background: "#1e1b26", color: "#fdd023", fontSize: "20px", lineHeight: "1",
        opacity: "0.7", padding: "0",
      });
      let timer, longPressed = false;
      btn.addEventListener("pointerdown", () => {
        longPressed = false;
        timer = setTimeout(() => { longPressed = true; toggleAmoled(); }, 600);
      });
      btn.addEventListener("pointerup", () => clearTimeout(timer));
      btn.addEventListener("pointerleave", () => clearTimeout(timer));
      btn.addEventListener("click", () => { if (!longPressed) toggleDark(); });
      document.body.appendChild(btn);
    };
    // Some managers inject after DOMContentLoaded despite @run-at document-start
    if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", addButton);
    else addButton();
  }
}
"""

out = (
    HEADER
    + "(() => {\n"
    + SHIM.replace("__CSS__", json.dumps(css))
    + "\n// ---------- content.js ----------\n"
    + content_js
    + TOGGLES
    + "})();\n"
)

dist = ROOT / "dist"
dist.mkdir(exist_ok=True)
(dist / "lsu-moodle-dark.user.js").write_text(out, encoding="utf-8")
print(f"wrote dist/lsu-moodle-dark.user.js ({len(out) // 1024} KB, v{manifest['version']})")

# ---------- Chrome Web Store package: only what the extension loads at runtime ----------
import zipfile

runtime = ["manifest.json", "dark.css", "content.js", "popup.html", "popup.js",
           *[f"icons/icon-{s}.png" for s in (16, 32, 48, 128)]]
missing = [f for f in runtime if not (ROOT / f).exists()]
if missing:
    raise SystemExit(f"missing files for the store package: {missing} (run make_icons.py?)")
zip_path = dist / f"lsu-moodle-dark-{manifest['version']}.zip"
with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
    for f in runtime:
        z.write(ROOT / f, f)
print(f"wrote dist/{zip_path.name} (upload this to the Chrome Web Store)")
